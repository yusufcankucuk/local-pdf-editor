async page => {
  await page.addInitScript(() => {window.confirm=()=>true;window.addEventListener('beforeunload',e=>e.stopImmediatePropagation(),{capture:true});});
  await page.evaluate(() => {window.confirm=()=>true;window.addEventListener('beforeunload',e=>e.stopImmediatePropagation(),{capture:true});});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto("http://127.0.0.1:5173/?context-test="+Date.now());
  await page.locator('.main-paper .textLayer span').first().waitFor();
  const button = name => page.getByRole('button',{name,exact:true});
  const assert = (value,message) => {if(!value) throw new Error(message);};
  await button('Metin').click();
  await page.locator('.annotation-overlay').click({position:{x:100,y:240}});
  const text = page.getByRole('textbox',{name:'Seçili metni düzenle'});
  await text.fill('Çağrı: ölçü ve çalışma.');
  await page.getByRole('combobox',{name:'Yazı tipi',exact:true}).selectOption('serif');
  await page.getByRole('spinbutton',{name:'Yazı boyutu',exact:true}).fill('32');
  await page.getByLabel('Seçili ekleme rengi').fill('#ba3344');
  const svgText=page.locator('.annotation-overlay text');
  assert(await svgText.getAttribute('font-family')==='PdfEditorSerif','Serif preview');
  assert(await svgText.getAttribute('font-size')==='32','Size preview');
  assert(await svgText.getAttribute('fill')==='#ba3344','Color preview');
  assert((await svgText.textContent()).includes('Çağrı'),'Text committed');
  await button('Geri al').click();
  assert(await svgText.getAttribute('fill')!=='#ba3344','Undo color');
  await button('İleri al').click();
  const downloadEvent=page.waitForEvent('download');
  await button('PDF indir').click();
  await (await downloadEvent).saveAs('artifacts/context-text.pdf');
  await button('Kopyala').click();
  assert(await svgText.count()===2,'Duplicate text');
  await button('Geri al').click();
  assert(await svgText.count()===1,'Undo duplicate');
  await page.keyboard.press('Escape');
  await svgText.click();
  const panel = await page.locator('.text-editor-panel').boundingBox();
  const stage = await page.locator('.document-stage').boundingBox();
  assert(panel.x >= stage.x + stage.width - 1, 'Text panel reserves right column');
  await page.screenshot({path:'artifacts/context-desktop.png'});
  await button('Düzenlemeyi kapat').click();
  await svgText.click();
  await page.getByRole('combobox',{name:'Yazı tipi',exact:true}).selectOption('mono');
  assert(await svgText.getAttribute('font-family')==='PdfEditorMono','Reselect and edit font');
  await page.setViewportSize({width:390,height:844});
  await page.locator('.text-editor-panel').scrollIntoViewIfNeeded();
  const box=await page.locator('.text-editor-panel').boundingBox();
  assert(box.x>=0 && box.x+box.width<=390,'Mobile panel width');
  const mobileStage=await page.locator('.document-stage').boundingBox();
  assert(box.y>=mobileStage.y+mobileStage.height-1,'Mobile panel below document');
  await page.screenshot({path:'artifacts/context-mobile.png'});
  await page.setViewportSize({width:320,height:740});
  await page.locator('.text-editor-panel').scrollIntoViewIfNeeded();
  const small=await page.locator('.text-editor-panel').boundingBox();
  assert(small.x>=0 && small.x+small.width<=320,'320px panel width');
  await page.keyboard.press('Escape');
  assert(await page.locator('.context-tools').count()===0,'Escape dismiss');
  await page.setViewportSize({width:1440,height:1000});
  await svgText.click();
  await page.locator('.document-name').click();
  await page.keyboard.press('Delete');
  assert(await svgText.count()===0,'Delete selected overlay');
  await button('Geri al').click();
  assert(await svgText.count()===1,'Undo deletion');
  await page.locator('input[aria-label="PDF dosyası seç"]').setInputFiles('artifacts/context-text.pdf');
  await page.getByRole('heading',{name:'context-text.pdf',exact:true}).waitFor();
  await page.waitForFunction(()=>document.querySelector('.main-paper .textLayer')?.textContent.includes('Çağrı: ölçü ve çalışma.'));
  const popupEvent=page.waitForEvent('popup');
  await button('Yazdırma görünümü').click();
  const popup=await popupEvent;
  await page.waitForFunction(()=>document.querySelector('.editor-notice')?.textContent.includes('Yazdırma görünümü açıldı'));
  assert(popup.url().startsWith('blob:'),'Local print PDF');
  await popup.close();
  return {passed:true,checks:['direct text entry','font/size/color','undo/redo','PDF export','reselect','320/390px placement','duplicate and undo','Escape','Delete and undo','exported Turkish text reopens','local print view']};
}
