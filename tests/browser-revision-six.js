async page => {
  const assert=(v,m)=>{if(!v)throw new Error(m)};
  const errors=[],requests=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>requests.push({url:r.url(),method:r.method()}));
  await page.addInitScript(()=>{window.confirm=()=>true;window.addEventListener('beforeunload',e=>e.stopImmediatePropagation(),{capture:true})});
  await page.setViewportSize({width:1440,height:1000});
  const origin=new URL(page.url()).origin;
  await page.goto(origin+'/?rev6='+Date.now());
  const button=name=>page.getByRole('button',{name,exact:true});
  const load=async(path,title)=>{await page.locator('input[aria-label="PDF dosyası seç"]').setInputFiles(path);await page.getByRole('heading',{name:title,exact:true}).waitFor();await page.locator('.main-paper canvas').waitFor();};
  await load('tests/fixtures/scanned-text.pdf','scanned-text.pdf');
  await button('Taramadan görsel alanı seç').waitFor();
  assert(await page.getByRole('button',{name:'PDF görselini düzenle',exact:true}).count()===0,'No fullpage image trap');
  const before=await page.locator('.main-paper canvas').evaluate(c=>c.toDataURL());
  await button('PDF görsellerini göster').click();
  await page.getByRole('button',{name:'1. PDF görselini düzenle',exact:true}).click();
  await page.getByLabel('Seçili görsel genişliği').waitFor();
  await page.waitForFunction(()=>!document.querySelector('.pdf-loading'));
  assert(await page.locator('.annotation-overlay image').count()===0,'Native scan kept in source');
  await page.waitForFunction(expected=>document.querySelector('.main-paper canvas')?.toDataURL()===expected,before);
  await button('Geri al').click();
  await button('Taramadan görsel alanı seç').click();
  const r=await page.locator('.native-targets').boundingBox();
  await page.mouse.move(r.x+90,r.y+110);await page.mouse.down();await page.mouse.move(r.x+300,r.y+170,{steps:10});await page.mouse.up();
  await page.locator('.annotation-overlay image').waitFor();
  const image=page.locator('.annotation-overlay image');
  assert(Number(await image.getAttribute('width'))<300,'Crop selects region, not whole scan');
  await button('Eklemeyi sil').click();
  await button('Geri al').click();
  await image.waitFor();
  const download=page.waitForEvent('download');await button('PDF indir').click();await(await download).saveAs('artifacts/revision-six-scan.pdf');
  await page.keyboard.press('Escape');
  await button('Taranmış yazıyı tanı').click();
  await page.getByRole('button',{name:/Taranmış metni düzenle/}).first().waitFor({timeout:120000});
  const hits=page.getByRole('button',{name:/Taranmış metni düzenle/});
  assert(await hits.count()>2,'OCR targets use actual line regions');
  await hits.last().click();
  await page.getByRole('region',{name:'Metin düzenleme paneli'}).waitFor();
  const panel=await page.locator('.text-editor-panel').boundingBox(),stage=await page.locator('.document-stage').boundingBox();
  assert(panel.x>=stage.x+stage.width-1,'Text panel alongside page');
  await page.getByRole('textbox',{name:'Seçili metni düzenle'}).fill('Yerel düzenleme kontrolü.');
  await button('Bitti').click();
  await page.locator('.annotation-overlay text').waitFor({state:'visible'});
  await page.screenshot({path:'artifacts/revision-six-scan.png'});
  await load('tests/fixtures/overlapping-images.pdf','overlapping-images.pdf');
  await page.getByRole('button',{name:'PDF görselini düzenle',exact:true}).last().click();
  await page.getByLabel('Seçili görsel genişliği').fill('140');
  const changed=page.waitForEvent('download');await button('PDF indir').click();await(await changed).saveAs('artifacts/revision-six-images.pdf');
  await page.getByRole('button',{name:'Eklemeyi sil',exact:true}).click();
  await button('Geri al').click();
  await page.screenshot({path:'artifacts/revision-six-digital.png'});
  assert(errors.length===0,'No page errors: '+errors.join(','));
  assert(requests.every(r=>r.method==='GET'&&(r.url.startsWith(origin+'/')||r.url.startsWith('blob:')||r.url.startsWith('data:'))),'Local reads only');
  return {passed:true,checks:['scan selection preserves pixels','scan region crop/delete/undo/export','real local OCR line hitboxes','right text panel','native resize/delete/export'],errors};
}
