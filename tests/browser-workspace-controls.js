async page => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const origin = new URL(page.url()).origin;
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    window.confirm = () => true;
    window.addEventListener('beforeunload', event => event.stopImmediatePropagation(), {capture:true});
  });
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(origin+'/?workspace-controls='+Date.now());
  const button = name => page.getByRole('button', {name, exact:true});
  assert(!/folio/i.test(await page.title()), 'No brand in title');
  assert(!/folio/i.test(await page.locator('body').innerText()), 'No brand in interface');
  assert(await page.locator('.brand').count()===0, 'No brand logo');
  await page.locator('input[aria-label="PDF dosyası seç"]').setInputFiles('tests/fixtures/scanned-notebook.pdf');
  await button('Yazı alanını seç').waitFor({timeout:60000});
  await button('Taranmış yazıyı tanı').click();
  await page.getByRole('button', {name:/Taranmış metni düzenle/}).first().waitFor({timeout:120000});
  await button('Düzenleme araçlarını kapat').click();
  assert(await page.locator('.scan-text-controls,.ocr-status,.content-hint,.scan-region-tools').count()===0, 'All editing rows close');
  assert(await page.getByRole('button', {name:/Taranmış metni düzenle/}).count()===0, 'OCR hitboxes hidden');
  await button('Yakınlaştır').click();
  assert(await page.locator('.scan-text-controls').count()===0, 'Closed state persists after render');
  await button('Düzenleme araçlarını göster').click();
  await page.getByRole('button', {name:/Taranmış metni düzenle/}).first().waitFor();
  await button('Taranmış yazıyı tanı').click();
  await button('Düzenleme araçlarını kapat').click();
  assert(await button('Taranmış yazıyı tanı').isEnabled(), 'Closing cancels OCR');
  await button('PDF içeriğini düzenle').click();
  await button('Yazı alanını seç').waitFor();
  await button('Düzenleme araçlarını kapat').click();
  await page.locator('input[aria-label="PDF dosyası seç"]').setInputFiles('tests/fixtures/native-image.pdf');
  await button('PDF görselini düzenle').waitFor({timeout:60000});
  await button('PDF görselini düzenle').click();
  const popup = page.getByRole('region', {name:'Yerinde düzenleme', exact:true});
  const handle = button('Araç penceresini taşı');
  await handle.waitFor();
  const before = await popup.boundingBox(), grip = await handle.boundingBox();
  await page.mouse.move(grip.x+grip.width/2,grip.y+grip.height/2);
  await page.mouse.down();
  await page.mouse.move(grip.x+grip.width/2+140,grip.y+grip.height/2-130,{steps:10});
  await page.mouse.up();
  const moved = await popup.boundingBox();
  assert(moved.x>before.x+100 && moved.y<before.y-100, 'Popup dragged');
  const image=page.locator('.main-paper [data-native-image]');
  const oldWidth=await image.getAttribute('width');
  await page.getByLabel('Seçili görsel genişliği').fill('180');
  await page.waitForFunction(()=>document.querySelector('.main-paper [data-native-image]')?.getAttribute('width')==='180');
  const after=await popup.boundingBox();
  assert(Math.abs(after.x-moved.x)<2 && Math.abs(after.y-moved.y)<2, 'Manual position survives image edits');
  await handle.focus();await page.keyboard.press('ArrowLeft');
  assert(Math.abs((await popup.boundingBox()).x-after.x+10)<2, 'Keyboard moves popup');
  assert(await image.getAttribute('width')==='180', 'Popup keyboard does not move object');
  await page.screenshot({path:'artifacts/workspace-controls-desktop.png'});
  for (const width of [390,320]) {
    await page.setViewportSize({width,height:844});
    await page.waitForFunction(()=>{const r=document.querySelector('.context-tools')?.getBoundingClientRect();return r && r.left>=0 && r.right<=innerWidth && r.bottom<=innerHeight;});
    await handle.focus();
    for(let i=0;i<40;i++) await page.keyboard.press('Shift+ArrowRight');
    const r=await popup.boundingBox();
    assert(r.x>=0 && r.x+r.width<=width+1, 'Popup clamped on mobile');
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth), 'No mobile overflow');
    await page.screenshot({path:'artifacts/workspace-controls-'+width+'.png'});
  }
  await button('Düzenlemeyi kapat').click();
  assert(await popup.count()===0, 'Popup closes');
  await button('Geri al').click();
  await page.waitForFunction(old=>document.querySelector('.main-paper [data-native-image]')?.getAttribute('width')===old,oldWidth);
  assert(errors.length===0, 'No browser errors: '+errors.join());
  return {passed:true,checks:['close/reopen OCR controls','close cancels OCR','unbranded interface','popup drag/persist/keyboard','resize/undo','320/390px'],errors};
}
